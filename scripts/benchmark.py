"""Benchmark: B-Tree index lookup vs linear scan on N synthetic records.

All numbers printed are MEASURED on whatever machine runs this - nothing is hard-coded.
Usage: python scripts/benchmark.py [N]      (default N = 100000)
"""
import os, platform, random, sys, tempfile, time
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from minidb import Database

N = int(sys.argv[1]) if len(sys.argv) > 1 else 100_000
rnd = random.Random(42)                       # fixed seed -> reproducible synthetic data
CITIES = ["Delhi", "Mumbai", "Pune", "Chennai", "Kolkata", "Jaipur"]

tmp = tempfile.mkdtemp(prefix="minidb_bench_")
db = Database(tmp)
t = db.create_table("users", {"id": "int", "name": "text", "city": "text", "balance": "float"}, "id")

t0 = time.perf_counter()
ids = list(range(1, N + 1)); rnd.shuffle(ids)                # random insertion order (harder for a tree)
for i in ids:
    t.insert({"id": i, "name": f"user_{i}", "city": rnd.choice(CITIES), "balance": round(rnd.uniform(0, 1e5), 2)})
t_ins = time.perf_counter() - t0

K = 2000
keys = [rnd.randint(1, N) for _ in range(K)]
t.index.nodes_visited = 0
t0 = time.perf_counter()
for k in keys: assert t.get(k)["id"] == k
t_idx = (time.perf_counter() - t0) / K
visited = t.index.nodes_visited / K

S = 10
t0 = time.perf_counter()
for k in keys[:S]: assert t.scan_find(k)["id"] == k
t_scan = (time.perf_counter() - t0) / S

t0 = time.perf_counter(); r = t.select(pk_min=1000, pk_max=1999); t_rng = time.perf_counter() - t0
t0 = time.perf_counter(); u = t.update(keys[0], {"balance": 1.0}); t_upd = time.perf_counter() - t0
t0 = time.perf_counter(); t.delete(keys[1]); t_del = time.perf_counter() - t0

lines = [
    f"Benchmark on {N:,} synthetic rows (seed 42)  |  Python {platform.python_version()} on {platform.system()}",
    f"B-Tree: min degree t={t.btree_t}, height={t.index.height()} levels",
    f"INSERT   : {t_ins:.2f}s total  ({N / t_ins:,.0f} rows/s)",
    f"INDEX    : {t_idx * 1e6:9.1f} us per point lookup  ({visited:.1f} B-Tree nodes visited on average)",
    f"SCAN     : {t_scan * 1e3:9.1f} ms per point lookup  (linear scan of the data file, O(N))",
    f"SPEEDUP  : ~{t_scan / t_idx:,.0f}x for point lookups at N={N:,}",
    f"RANGE    : {len(r)} rows (id 1000..1999) in {t_rng * 1e3:.1f} ms via index range scan",
    f"UPDATE   : {t_upd * 1e6:.0f} us   DELETE: {t_del * 1e6:.0f} us (single row)",
    f"Data file: {t.heap.size() / 1e6:.1f} MB",
]
print("\n".join(lines))
db.close()
out = os.path.join(os.path.dirname(__file__), "..", "sample_output", "benchmark.txt")
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n(Generated by scripts/benchmark.py - re-run it; numbers vary by machine.)\n")
